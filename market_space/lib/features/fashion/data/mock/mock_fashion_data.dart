  static List<FashionProductModel> getFeaturedProducts() =>
      products.where((p) => p.isFeatured).toList();

  static List<FashionProductModel> getBestSellers() =>
      products.where((p) => p.isBestSeller).toList();

  static List<FashionProductModel> getNewArrivals() =>
      products.where((p) => p.isNewArrival).toList();

  static List<FashionProductModel> getProductsByDepartment(FashionDepartment dept) =>
      products.where((p) => p.department == dept).toList();

  static List<FashionProductModel> getProductsByCategory(String category) =>
      products.where((p) => p.category == category).toList();

  static FashionProductModel getProductById(String id) {
    return products.firstWhere(
      (p) => p.id == id,
      orElse: () => products.first,
    );
  }

  static List<FashionProductModel> getSimilarProducts(FashionProductModel product) {
    return products
        .where((p) => p.id != product.id && (p.department == product.department || p.category == product.category))
        .take(4)
        .toList();
  }
