  static List<CarListingModel> getFeaturedCars() =>
      listings.where((c) => c.isFeatured).toList();

  static List<CarListingModel> getLatestCars() =>
      List<CarListingModel>.from(listings)
        ..sort((a, b) => b.createdAt.compareTo(a.createdAt));

  static List<CarListingModel> getCarsByBrand(String brand) =>
      listings.where((c) => c.brand.toLowerCase() == brand.toLowerCase()).toList();

  static List<CarListingModel> getCarsByBodyType(CarBodyType bodyType) =>
      listings.where((c) => c.bodyType == bodyType).toList();

  static CarListingModel getCarById(String id) {
    return listings.firstWhere(
      (c) => c.id == id,
      orElse: () => listings.first,
    );
  }

  static List<CarListingModel> getSimilarCars(CarListingModel car) {
    return listings
        .where((c) => c.id != car.id && (c.brand == car.brand || c.bodyType == car.bodyType))
        .take(4)
        .toList();
  }
